//! Source-derived component expectations, not an independent .NET export.

use parrot_provider::http_stream::{HttpError, SseDecoder, SseEvent};

type Outcome = Result<SseEvent, String>;

fn event(name: &str, data: &str, id: &str) -> Outcome {
    Ok(SseEvent {
        event: name.to_owned(),
        data: data.to_owned(),
        id: id.to_owned(),
    })
}

fn too_large(max: i32) -> Outcome {
    Err(format!("sse: event exceeds maximum size {max}"))
}

fn normalize(result: Result<SseEvent, HttpError>) -> Outcome {
    result.map_err(|error| match error {
        HttpError::Wire(message) => message,
        other => panic!("unexpected error: {other:?}"),
    })
}

fn assert_chunks(chunks: &[&[u8]], max: i32, expected: &[Outcome]) {
    let mut decoder = SseDecoder::new(max);
    let mut actual = Vec::new();
    for chunk in chunks {
        actual.extend(decoder.feed(chunk).into_iter().map(normalize));
    }
    actual.extend(decoder.finish().into_iter().map(normalize));
    assert_eq!(actual, expected, "chunks={chunks:?}, max={max}");
    assert!(decoder.finish().is_empty());
    assert!(decoder.feed(b"data:after\n\n").is_empty());
}

/// Every two-part split and byte-at-a-time input, plus every possible partition
/// for small vectors. Expectations are fixed below, never generated by decoder.
fn assert_partitions(input: &[u8], max: i32, expected: &[Outcome]) {
    assert_chunks(&[input], max, expected);
    for split in 0..=input.len() {
        assert_chunks(&[&input[..split], &input[split..]], max, expected);
    }
    let single_bytes: Vec<_> = input.chunks(1).collect();
    assert_chunks(&single_bytes, max, expected);
    if !input.is_empty() && input.len() <= 15 {
        for boundaries in 0..(1usize << (input.len() - 1)) {
            let mut chunks = Vec::new();
            let mut start = 0;
            for end in 1..input.len() {
                if boundaries & (1 << (end - 1)) != 0 {
                    chunks.push(&input[start..end]);
                    start = end;
                }
            }
            chunks.push(&input[start..]);
            assert_chunks(&chunks, max, expected);
        }
    }
}

#[test]
fn records_survive_every_small_byte_partition() {
    assert_partitions(b"data:x\n\n", 100, &[event("", "x", "")]);
    assert_partitions(b"data:\r\n\r\n", 100, &[event("", "", "")]);
    assert_partitions(b"data\r\r", 100, &[event("", "", "")]);
    assert_partitions(
        b"data:x\r\r\ndata:y\n\r",
        100,
        &[event("", "x", ""), event("", "y", "")],
    );
}

#[test]
fn unicode_and_invalid_utf8_are_partition_independent() {
    for (input, data) in [
        ("data:é\n\n".as_bytes(), "é"),
        ("data:😀\n\n".as_bytes(), "😀"),
        (b"data:\xe2\x82\n\n".as_slice(), "�"),
        (b"data:\xff\n\n".as_slice(), "�"),
        (b"data:\xed\xa0\x80\n\n".as_slice(), "���"),
        (b"data:\xf0\x80\x80\x80\n\n".as_slice(), "����"),
        (b"data:\xe2(\xa1\n\n".as_slice(), "�(�"),
    ] {
        assert_partitions(input, 100, &[event("", data, "")]);
    }
}

#[test]
fn only_initial_utf8_preamble_is_consumed() {
    assert_partitions(b"\xef\xbb\xbfdata:x\n\n", 8, &[event("", "x", "")]);
    assert_partitions(b"\xef\xbb\xbf", 1, &[]);
    assert_partitions(b"\xef\xbb\xbf\n", 1, &[]);
    assert_partitions(b"\xef\xbb", 1, &[too_large(1)]);
    assert_partitions(b"\xef\xbb\xbf\xef\xbb\xbfdata:x\n\n", 100, &[]);
    assert_partitions(b"\n\xef\xbb\xbfdata:x\n\n", 100, &[]);
    assert_partitions(b"\xff\xfedata:x\n\n", 100, &[]);
    assert_partitions(
        "data:\u{feff}\n\n".as_bytes(),
        100,
        &[event("", "\u{feff}", "")],
    );
}

#[test]
fn field_names_values_and_record_resets_follow_source() {
    assert_partitions(
        b":comment\nunknown:x\nEvent:ignored\nevent:old\nevent: new\nid: first\nid: second\ndata: a:b\ndata:  b\ndata\n\ndata:z\n\n",
        1000,
        &[event("new", "a:b\n b\n", "second"), event("", "z", "")],
    );
    assert_partitions(
        b"event\n\nid\n\n",
        100,
        &[event("", "", ""), event("", "", "")],
    );
    assert_partitions(b" :ignored\nDATA:x\nunknown\n\n", 100, &[]);
}

#[test]
fn nul_id_is_ignored_but_still_makes_a_record() {
    assert_partitions(b"id:\0\n\n", 100, &[event("", "", "")]);
    assert_partitions(b"id:kept\nid:bad\0id\n\n", 100, &[event("", "", "kept")]);
    assert_partitions(b"id:bad\0id", 100, &[event("", "", "")]);
}

#[test]
fn non_cr_lf_controls_stay_inside_lines() {
    let data = "\0\u{b}\u{c}\u{85}\u{2028}\u{2029}";
    let input = format!("data:{data}\n\n");
    assert_partitions(input.as_bytes(), 100, &[event("", data, "")]);
    assert_partitions(b"data:\t x\n\n", 100, &[event("", "\t x", "")]);
}

#[test]
fn limit_counts_utf16_units_and_one_per_line() {
    assert_partitions("data:é\n\n".as_bytes(), 8, &[event("", "é", "")]);
    assert_partitions("data:😀\n\n".as_bytes(), 9, &[event("", "😀", "")]);
    assert_partitions("data:😀\n\n".as_bytes(), 8, &[too_large(8)]);
    assert_partitions(b"data:\xff\n\n", 8, &[event("", "�", "")]);
    assert_partitions(b"data:x\r\n\r\n", 8, &[event("", "x", "")]);
    assert_partitions(b"data:x", 7, &[event("", "x", "")]);
    assert_partitions(b"data:x\n\n", 7, &[too_large(7)]);
}

#[test]
fn comments_and_unknown_fields_also_consume_limit() {
    assert_partitions(b":123\ndata:x\n\n", 12, &[too_large(12)]);
    assert_partitions(b"x:12\ndata:x\n\n", 12, &[too_large(12)]);
    assert_partitions(b":123\ndata:x\n\n", 13, &[event("", "x", "")]);
    assert_partitions(b"x:12\ndata:x\n\n", 13, &[event("", "x", "")]);
    assert_partitions(b":123\n\ndata:x\n\n", 8, &[event("", "x", "")]);
    assert_partitions(b"\n\n\n", 1, &[]);
}

#[test]
fn final_unterminated_lines_and_replacement_are_flushed_once() {
    assert_partitions(b"", 100, &[]);
    assert_partitions(b"data:x", 100, &[event("", "x", "")]);
    assert_partitions(b"data:x\n", 100, &[event("", "x", "")]);
    assert_partitions(b"data:x\r", 100, &[event("", "x", "")]);
    assert_partitions(b"data:\xe2\x82", 100, &[event("", "�", "")]);
    assert_partitions(b"event:name\nid:only", 100, &[event("name", "", "only")]);
    assert_partitions(b":comment", 100, &[]);
    assert_partitions(b"unknown:x", 100, &[]);
}

#[test]
fn size_error_is_terminal_and_preserves_prior_chunk_events() {
    assert_partitions(
        b"data:a\n\ndata:oversized\n\ndata:b\n\n",
        8,
        &[event("", "a", ""), too_large(8)],
    );
    assert_partitions(
        b"data:a\n\ndata:oversized",
        8,
        &[event("", "a", ""), too_large(8)],
    );
    let mut decoder = SseDecoder::new(1);
    assert!(decoder.feed(b"data:too-long").is_empty());
    let errors: Vec<_> = decoder
        .feed(b"\ndata:x\n\n")
        .into_iter()
        .map(normalize)
        .collect();
    assert_eq!(errors, [too_large(1)]);
    assert!(decoder.feed(b"data:y\n\n").is_empty());
    assert!(decoder.finish().is_empty());
}

#[test]
fn nonpositive_limits_use_the_default() {
    for max in [0, -1, i32::MIN] {
        assert_partitions(b"data:x\n\n", max, &[event("", "x", "")]);
    }
    // The default is 4 Mi UTF-16 units including all line terminators.
    let mut input = b"data:".to_vec();
    input.resize((4 << 20) - 2, b'x');
    input.extend_from_slice(b"\n\n");
    let mut decoder = SseDecoder::new(0);
    let output = decoder.feed(&input);
    assert_eq!(output.len(), 1);
    assert_eq!(output[0].as_ref().unwrap().data.len(), (4 << 20) - 7);
    let mut decoder = SseDecoder::new(-1);
    input.insert(5, b'x');
    let output: Vec<_> = decoder.feed(&input).into_iter().map(normalize).collect();
    assert_eq!(output, [too_large(4 << 20)]);
}
