'use strict';

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const input = process.argv[2];
if (!input) throw new Error('Pass UnicodeData.txt from https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt');
const output = path.resolve(__dirname, '../ordinal_uppercase.rs');
const expectedHash = 'ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f';
const data = fs.readFileSync(input);
if (crypto.createHash('sha256').update(data).digest('hex') !== expectedHash) {
    throw new Error('Unicode 16.0.0 source checksum differs from the retained official input');
}
const isScalar = n => n >= 0 && n <= 0x10ffff && !(n >= 0xd800 && n <= 0xdfff);
const pairs = [];
let previous = -1;
for (const line of data.toString('utf8').split(/\r?\n/)) {
    if (line === '') continue;
    const fields = line.split(';');
    if (fields.length !== 15) throw new Error('UnicodeData row must have exactly 15 fields');
    const from = Number.parseInt(fields[0], 16);
    if (!Number.isInteger(from) || from <= previous || from > 0x10ffff) {
        throw new Error('UnicodeData code points must be unique and increasing');
    }
    previous = from;
    if (fields[12] === '') continue;
    const to = Number.parseInt(fields[12], 16);
    if (!isScalar(from) || !Number.isInteger(to) || !isScalar(to)) {
        throw new Error('Simple uppercase mapping must contain valid Unicode scalars');
    }
    if (from !== to) pairs.push([from, to]);
}
const escape = n => `\\u{${n.toString(16).toUpperCase().padStart(4, '0')}}`;
const text = [
    '// @generated by src/terminal_dialogs/unicode/generate.cjs.',
    '// Source: https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt',
    `// SHA-256: ${expectedHash}`,
    '// Unicode-3.0 license: LICENSES/Unicode-3.0.txt; official input URL is listed above.',
    '// All nonidentity field-12 simple-uppercase mappings; no full casing or folding.',
    '',
    'pub(super) const SIMPLE_UPPERCASE: &[(char, char)] = &[',
    ...pairs.map(([from, to]) => `    ('${escape(from)}', '${escape(to)}'),`),
    '];',
    ''
].join('\n');
fs.writeFileSync(output, text);
console.log(`Generated ${pairs.length} Unicode 16.0.0 mappings`);
