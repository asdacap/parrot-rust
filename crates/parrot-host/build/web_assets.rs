use std::fs;
use std::io;
use std::path::{Path, PathBuf};

#[derive(Debug, Clone, PartialEq, Eq)]
struct Asset {
    path: String,
    content_type: &'static str,
    source: PathBuf,
}

/// Generate a Rust static table for every file in Vite's `dist` directory.
///
/// The generated code embeds the original asset bytes with `include_bytes!`,
/// preserving the same inventory and content as the browser build. This helper
/// deliberately has no Cargo/build-script dependency so it can be unit-tested
/// independently of shared workspace registration.
pub fn generate_embedded_assets(web_dist: &Path, output: &Path) -> io::Result<()> {
    let index = web_dist.join("index.html");
    if !index.is_file() {
        return Err(io::Error::new(
            io::ErrorKind::NotFound,
            format!("retained web build is missing {}", index.display()),
        ));
    }

    let mut assets = Vec::new();
    collect_assets(web_dist, web_dist, &mut assets)?;
    assets.sort_by(|a, b| a.path.cmp(&b.path));
    if assets.is_empty() {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            "retained web build contains no files",
        ));
    }

    let mut generated = String::from(
        "// Generated by crates/parrot-host/build/web_assets.rs; do not edit.\n\
         #[derive(Debug, Clone, Copy)]\n\
         pub struct EmbeddedWebAsset {\n\
             pub path: &'static str,\n\
             pub content_type: &'static str,\n\
             pub bytes: &'static [u8],\n\
         }\n\
         pub static EMBEDDED_WEB_ASSETS: &[EmbeddedWebAsset] = &[\n",
    );
    for asset in assets {
        use std::fmt::Write as _;
        writeln!(
            generated,
            "    EmbeddedWebAsset {{ path: {:?}, content_type: {:?}, bytes: include_bytes!({:?}) }},",
            asset.path,
            asset.content_type,
            asset.source.to_string_lossy(),
        )
        .expect("writing into a String cannot fail");
    }
    generated.push_str("];\n");

    if let Some(parent) = output.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(output, generated)
}

fn collect_assets(root: &Path, directory: &Path, assets: &mut Vec<Asset>) -> io::Result<()> {
    let mut children = fs::read_dir(directory)?.collect::<Result<Vec<_>, _>>()?;
    children.sort_by_key(|entry| entry.file_name());
    for child in children {
        let path = child.path();
        let metadata = fs::symlink_metadata(&path)?;
        if metadata.file_type().is_symlink() {
            return Err(io::Error::new(
                io::ErrorKind::InvalidData,
                format!("web build contains a symlink: {}", path.display()),
            ));
        }
        if metadata.is_dir() {
            collect_assets(root, &path, assets)?;
        } else if metadata.is_file() {
            let relative = path.strip_prefix(root).map_err(|_| {
                io::Error::new(
                    io::ErrorKind::InvalidData,
                    "asset escaped web build directory",
                )
            })?;
            let relative = relative
                .components()
                .map(|component| component.as_os_str().to_string_lossy())
                .collect::<Vec<_>>()
                .join("/");
            assets.push(Asset {
                path: relative,
                content_type: content_type(&path),
                source: path,
            });
        }
    }
    Ok(())
}

fn content_type(path: &Path) -> &'static str {
    match path.extension().and_then(|extension| extension.to_str()) {
        Some("html") => "text/html; charset=utf-8",
        Some("css") => "text/css; charset=utf-8",
        Some("js") | Some("mjs") => "text/javascript; charset=utf-8",
        Some("json") => "application/json; charset=utf-8",
        Some("svg") => "image/svg+xml",
        Some("png") => "image/png",
        Some("jpg") | Some("jpeg") => "image/jpeg",
        Some("gif") => "image/gif",
        Some("ico") => "image/x-icon",
        Some("woff") => "font/woff",
        Some("woff2") => "font/woff2",
        _ => "application/octet-stream",
    }
}

/// Cargo build-script entry point. Missing frontend output is a hard failure;
/// packaging a host with a silent placeholder UI would be misleading.
#[cfg(not(test))]
pub fn run() -> io::Result<()> {
    let manifest =
        PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").ok_or_else(|| {
            io::Error::new(io::ErrorKind::NotFound, "CARGO_MANIFEST_DIR is not set")
        })?);
    let out_dir = PathBuf::from(
        std::env::var_os("OUT_DIR")
            .ok_or_else(|| io::Error::new(io::ErrorKind::NotFound, "OUT_DIR is not set"))?,
    );
    let workspace = manifest.join("../..");
    let web_dist = workspace.join("web/dist");
    println!("cargo:rerun-if-changed={}", web_dist.display());
    generate_embedded_assets(&web_dist, &out_dir.join("web_assets.rs"))?;
    Ok(())
}
